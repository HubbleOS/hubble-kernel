#pragma once

#include <stdint.h>

// ============================================================================
// Структура для сохранения состояния регистров
// ============================================================================

typedef struct
{
	// Сегментные регистры
	uint64_t ds;

	// Регистры общего назначения (сохранены вручную)
	uint64_t r15, r14, r13, r12, r11, r10, r9, r8;
	uint64_t rbp, rdi, rsi, rdx, rcx, rbx, rax;

	// Номер прерывания и код ошибки
	uint64_t int_no, err_code;

	// Автоматически сохранено процессором при прерывании
	uint64_t rip, cs, rflags, rsp, ss;
} __attribute__((packed)) registers_t;

// ============================================================================
// Типы обработчиков
// ============================================================================

typedef void (*irq_handler_t)(registers_t *regs);

// ============================================================================
// Функции инициализации
// ============================================================================

void interrupts_init(void);
void pic_remap(void);

// ============================================================================
// Управление IRQ
// ============================================================================

void pic_send_eoi(uint8_t irq);
void irq_set_mask(uint8_t irq);
void irq_clear_mask(uint8_t irq);
void irq_install_handler(uint8_t irq, irq_handler_t handler);
void irq_uninstall_handler(uint8_t irq);

// ============================================================================
// Обработчики (вызываются из ассемблера)
// ============================================================================

void isr_handler(registers_t *regs);
void irq_handler(registers_t *regs);
uint64_t syscall_handler(uint64_t num, uint64_t a1, uint64_t a2, uint64_t a3,
			 uint64_t a4, uint64_t a5, uint64_t a6);
uint64_t syscall_handler_wrapper(registers_t *regs);
